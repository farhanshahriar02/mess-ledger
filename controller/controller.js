
class MessController {
  constructor(model, view) {
    this.model = model;
    this.view  = view;
    this._init();
  }

  _init() {
    this.view.bindAddMember(() => this.handleAddMember());
    this.view.bindReset(() => this.handleReset());
    this.view.bindCopy(() => this.handleCopyReport());
    this.view.bindPDF(() => this.handleDownloadPDF());
    this.view.bindMemberInput((id, field, value) => this.handleMemberInput(id, field, value));
    this.view.bindRemoveMember((id) => this.handleRemoveMember(id));
    this.refresh();
  }

  refresh() { this.view.renderAll(this.model.getSummary()); }

  handleAddMember() {
    const member = this.model.addMember({
      name: `Roommate ${this.model.members.length + 1}`,
      meals: 0, bazar: 0, utility: 0,
    });
    this.refresh();
    this.view.focusMember(member.id);
  }

  handleRemoveMember(id) {
    if (!window.confirm('Remove this roommate from the ledger?')) return;
    this.model.removeMember(id);
    this.refresh();
  }

  handleMemberInput(id, field, value) {
    this.model.updateMember(id, field, value);
    this.view.updateLive(this.model.getSummary());
  }

  /* ---------- RESET: zero values, keep members ---------- */
  handleReset() {
    if (!window.confirm(
      'Reset all values to zero? '
    )) return;
    this.model.reset();
    this.refresh();
    this.view.showToast('All values reset to zero.');
  }

  async handleCopyReport() {
    const summary = this.model.getSummary();
    const report  = this.buildReport(summary);
    try {
      if (navigator.clipboard && window.isSecureContext) {
        await navigator.clipboard.writeText(report);
      } else {
        this._fallbackCopy(report);
      }
      this.view.showToast('Report copied! Paste it in WhatsApp.');
    } catch (err) {
      console.error('[MessController] Copy failed', err);
      this.view.showToast('Could not copy report. Please try again.');
    }
  }

  /* ---------- PDF Download ---------- */
  handleDownloadPDF() {
    const summary = this.model.getSummary();

    if (summary.memberCount === 0) {
      this.view.showToast('Add at least one roommate before downloading.');
      return;
    }
    if (!window.jspdf || !window.jspdf.jsPDF) {
      this.view.showToast('PDF library not loaded. Check your connection.');
      return;
    }

    try {
      const { jsPDF } = window.jspdf;
      const doc   = new jsPDF({ unit: 'mm', format: 'a4' });
      const pageW = doc.internal.pageSize.getWidth();
      const pageH = doc.internal.pageSize.getHeight();
      const margin = 15;
      const contentW = pageW - margin * 2;
      const taka = (v, d = 2) =>
        `Tk ${Number(v || 0).toLocaleString('en-US', {
          minimumFractionDigits: d,
          maximumFractionDigits: d,
        })}`;

      let y = margin;

      /* Title */
      doc.setFontSize(20);
      doc.setFont('helvetica', 'bold');
      doc.setTextColor(6, 78, 59);
      doc.text('Mess Meal & Cost Report', margin, y);
      y += 8;

      doc.setFontSize(10);
      doc.setFont('helvetica', 'normal');
      doc.setTextColor(100, 116, 139);
      doc.text(`Generated by Farhan bhai: ${new Date().toLocaleString()}`, margin, y);
      y += 10;

      /* Summary */
      doc.setFontSize(14);
      doc.setFont('helvetica', 'bold');
      doc.setTextColor(6, 78, 59);
      doc.text('Summary', margin, y);
      y += 6;

      doc.setFontSize(10);
      doc.setFont('helvetica', 'normal');
      doc.setTextColor(30, 41, 59);

      const summaryRows = [
        ['Total Bazar',      taka(summary.totalBazar, 0)],
        ['Total Meals',      summary.totalMeals.toLocaleString('en-US')],
        ['Total Utility',    taka(summary.totalUtility, 0)],
        ['Meal Rate',        taka(summary.mealRate, 2)],
        ['Utility / Person', taka(summary.utilityPerPerson, 2)],
      ];
      summaryRows.forEach(([k, v]) => {
        doc.text(k, margin + 2, y);
        doc.text(v, margin + 70, y);
        y += 6;
      });
      y += 4;

      /* Member breakdown table */
      doc.setFontSize(14);
      doc.setFont('helvetica', 'bold');
      doc.setTextColor(6, 78, 59);
      doc.text('Member Breakdown', margin, y);
      y += 6;

      const cols = [
        { label: 'Name',        w: 30, align: 'left'  },
        { label: 'Meals',       w: 14, align: 'right' },
        { label: 'Bazar',       w: 22, align: 'right' },
        { label: 'Utility',     w: 22, align: 'right' },
        { label: 'Meal Cost',   w: 24, align: 'right' },
        { label: 'Util Share',  w: 24, align: 'right' },
        { label: 'Total',       w: 22, align: 'right' },
        { label: 'Balance',     w: 22, align: 'right' },
      ];

      const drawHeader = () => {
        doc.setFillColor(6, 78, 59);
        doc.rect(margin, y - 4, contentW, 7, 'F');
        doc.setTextColor(255, 255, 255);
        doc.setFont('helvetica', 'bold');
        doc.setFontSize(9);
        let x = margin + 2;
        cols.forEach((col) => {
          if (col.align === 'right') {
            doc.text(col.label, x + col.w - 2, y, { align: 'right' });
          } else {
            doc.text(col.label, x, y);
          }
          x += col.w;
        });
        y += 7;
      };
      drawHeader();

      doc.setFontSize(9);
      summary.members.forEach((m, i) => {
        if (y > pageH - 30) {
          doc.addPage();
          y = margin;
          drawHeader();
        }

        if (i % 2 === 0) {
          doc.setFillColor(248, 250, 252);
          doc.rect(margin, y - 4, contentW, 7, 'F');
        }

        const values = [
          m.name.length > 14 ? m.name.slice(0, 13) + '…' : m.name,
          String(m.meals),
          taka(m.bazar, 0),
          taka(m.utility, 0),
          taka(m.mealCost, 2),
          taka(m.utilityShare, 2),
          taka(m.totalCost, 2),
          `${m.status === 'refund' ? '+' : m.status === 'due' ? '-' : ''}${taka(m.amount, 2)}`,
        ];

        let x = margin + 2;
        values.forEach((val, idx) => {
          if (idx === 7) {
            doc.setFont('helvetica', 'bold');
            if (m.status === 'refund')      doc.setTextColor(5, 150, 105);
            else if (m.status === 'due')    doc.setTextColor(194, 65, 12);
            else                            doc.setTextColor(100, 116, 139);
          } else {
            doc.setFont('helvetica', 'normal');
            doc.setTextColor(30, 41, 59);
          }
          const col = cols[idx];
          if (col.align === 'right') {
            doc.text(val, x + col.w - 2, y, { align: 'right' });
          } else {
            doc.text(val, x, y);
          }
          x += col.w;
        });
        y += 7;
      });

      /* Totals */
      y += 6;
      doc.setFont('helvetica', 'bold');
      doc.setFontSize(12);
      doc.setTextColor(6, 78, 59);
      doc.text('Totals', margin, y);
      y += 7;

      doc.setFontSize(10);
      doc.setFont('helvetica', 'normal');
      doc.setTextColor(30, 41, 59);
      doc.text('Total Refunds', margin + 2, y);
      doc.setFont('helvetica', 'bold');
      doc.setTextColor(5, 150, 105);
      doc.text(taka(summary.totalRefund, 2), margin + 70, y);
      y += 6;

      doc.setFont('helvetica', 'normal');
      doc.setTextColor(30, 41, 59);
      doc.text('Total Dues', margin + 2, y);
      doc.setFont('helvetica', 'bold');
      doc.setTextColor(194, 65, 12);
      doc.text(taka(summary.totalDue, 2), margin + 70, y);
      y += 6;

      doc.setFont('helvetica', 'normal');
      doc.setTextColor(30, 41, 59);
      doc.text('Ledger Status', margin + 2, y);
      doc.setFont('helvetica', 'bold');
      doc.text(summary.isBalanced ? 'Balanced' : 'Unbalanced', margin + 70, y);
      y += 10;

      /* Footer on all pages */
      const pageCount = doc.internal.getNumberOfPages();
      for (let i = 1; i <= pageCount; i++) {
        doc.setPage(i);
        doc.setFont('helvetica', 'normal');
        doc.setFontSize(8);
        doc.setTextColor(148, 163, 184);
        doc.text('Generated by MessLedger', margin, pageH - 8);
        doc.text(`Page ${i} of ${pageCount}`, pageW - margin, pageH - 8, { align: 'right' });
      }

      const dateStr = new Date().toISOString().slice(0, 10);
      doc.save(`messledger-report-${dateStr}.pdf`);
      this.view.showToast('PDF downloaded successfully!');
    } catch (err) {
      console.error('[MessController] PDF failed', err);
      this.view.showToast('Could not generate PDF. Please try again.');
    }
  }

  /* ---------- WhatsApp text report ---------- */
  buildReport(summary) {
    const c = summary.currency || '৳';
    const money = (v, d = 2) =>
      `${c}${Number(v || 0).toLocaleString('en-US', {
        minimumFractionDigits: d, maximumFractionDigits: d,
      })}`;

    const lines = [
      '*Mess Meal & Cost Report*',
      '--------------------------',
      `Total Bazar:        ${money(summary.totalBazar, 0)}`,
      `Total Meals:        ${summary.totalMeals.toLocaleString('en-US')}`,
      `Total Utility:      ${money(summary.totalUtility, 0)}`,
      `Meal Rate:          ${money(summary.mealRate, 2)}`,
      `Utility / Person:   ${money(summary.utilityPerPerson, 2)}`,
      '',
      '*Member Breakdown*',
    ];

    if (summary.members.length === 0) {
      lines.push('No members added.');
    } else {
      summary.members.forEach((m) => {
        const sign  = m.status === 'refund' ? '+' : m.status === 'due' ? '-' : '';
        const label = m.status === 'refund' ? 'Refund'
                    : m.status === 'due'    ? 'Due'
                    :                         'Settled';
        lines.push(
          `• ${m.name}\n` +
          `   Meals ${m.meals} | Bazar ${money(m.bazar, 0)} | Utility ${money(m.utility, 0)}\n` +
          `   Meal cost ${money(m.mealCost, 2)} + Utility share ${money(m.utilityShare, 2)} = ${money(m.totalCost, 2)}\n` +
          `   Balance: ${sign}${money(m.amount, 2)} (${label})`
        );
      });
    }

    lines.push('', '*Totals*');
    lines.push(`Total Refunds: ${money(summary.totalRefund, 2)}`);
    lines.push(`Total Dues:    ${money(summary.totalDue, 2)}`);
    lines.push(`Status: ${summary.memberCount === 0 ? 'No members'
              : summary.isBalanced ? 'Balanced' : 'Unbalanced'}`);
    lines.push('', 'Generated by MessLedger');
    return lines.join('\n');
  }

  _fallbackCopy(text) {
    const ta = document.createElement('textarea');
    ta.value = text;
    ta.setAttribute('readonly', '');
    ta.style.cssText = 'position:fixed;opacity:0;';
    document.body.appendChild(ta);
    ta.select();
    document.execCommand('copy');
    ta.remove();
  }
}


(function bootstrap() {
  function start() {
    const model      = new MessModel({ currency: '৳' });
    const view       = new MessView();
    const controller = new MessController(model, view);
    window.messLedger = { model, view, controller };
  }
  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', start);
  } else {
    start();
  }
})();